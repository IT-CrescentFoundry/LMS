def _rows(connection: sa.Connection, sql: str, **params: Any) -> list[sa.Row[Any]]:
    statement = sa.text(sql)
    expanding = [name for name, value in params.items() if isinstance(value, list | tuple)]
    if expanding:
        statement = statement.bindparams(*(sa.bindparam(n, expanding=True) for n in expanding))
    return list(connection.execute(statement, params))


def _seed() -> None:
    online = not context.is_offline_mode()
    if online:
        connection = op.get_bind()
        roles = {
            r.code
            for r in _rows(
                connection, "SELECT code FROM access_role WHERE code IN :c", c=list(ROLE_GRANTS)
            )
        }
        existing = [
            r.code
            for r in _rows(
                connection, "SELECT code FROM access_permission WHERE code IN :c", c=ALL_CODES
            )
        ]
        if set(ROLE_GRANTS) - roles or existing:
            raise RuntimeError(
                f"Revision 0011 cannot seed permissions: missing roles {sorted(set(ROLE_GRANTS) - roles)}, "
                f"existing codes {sorted(existing)}"
            )
    for code, description in PERMISSIONS:
        op.execute(
            permission.insert().values(
                code=code, description=description, is_privileged=False, created_at=NOW
            )
        )
    for role_code, codes in ROLE_GRANTS.items():
        op.execute(
            role_permission.insert().from_select(
                ["access_role_id", "access_permission_id", "granted_at"],
                sa.select(role.c.id, permission.c.id, NOW)
                .select_from(role.join(permission, sa.true()))
                .where(role.c.code == role_code, permission.c.code.in_(codes)),
            )
        )
    for code, name, gap_method, competent, plan_gap, note, levels in SCALES:
        op.execute(
            scale_table.insert().values(
                public_id=NEW_ID,
                code=code,
                name=name,
                gap_method=gap_method,
                competent_rank=competent,
                plan_gap_steps=plan_gap,
                source_note=note,
                is_active=True,
                created_at=NOW,
                updated_at=NOW,
                version=1,
            )
        )
        for rank, level_code, label in levels:
            op.execute(
                level_table.insert().from_select(
                    ["public_id", "scale_id", "rank", "code", "label", "numeric_value"],
                    sa.select(
                        NEW_ID,
                        sa.text("id"),
                        sa.literal(rank),
                        sa.literal(level_code),
                        sa.literal(label),
                        sa.literal(rank),
                    )
                    .select_from(sa.text("proficiency_scale"))
                    .where(sa.text("code = :scale_code").bindparams(scale_code=code)),
                )
            )
    if online:
        problems = seed_problems(op.get_bind())
        if problems:
            raise RuntimeError(
                "Revision 0011 did not establish the expected seed: " + "; ".join(problems)
            )


def seed_problems(connection: sa.Connection) -> list[str]:
    problems: list[str] = []
    perms = _rows(
        connection,
        "SELECT id, code, description, is_privileged FROM access_permission WHERE code IN :c",
        c=ALL_CODES,
    )
    expected = dict(PERMISSIONS)
    if {p.code for p in perms} != set(ALL_CODES):
        problems.append(f"permissions present {sorted(p.code for p in perms)}")
    for p in perms:
        if p.description != expected.get(p.code) or p.is_privileged:
            problems.append(f"permission {p.code} was modified")
    mappings = _rows(
        connection,
        "SELECT r.code AS role_code, p.code AS permission_code, m.granted_by_user_id "
        "FROM access_role_permission m JOIN access_role r ON r.id = m.access_role_id "
        "JOIN access_permission p ON p.id = m.access_permission_id WHERE p.code IN :c",
        c=ALL_CODES,
    )
    actual = {(m.role_code, m.permission_code) for m in mappings}
    if actual != EXPECTED_MAPPINGS or len(mappings) != len(EXPECTED_MAPPINGS):
        problems.append(f"role-permission mappings differ: {sorted(actual ^ EXPECTED_MAPPINGS)}")
    if any(m.granted_by_user_id for m in mappings):
        problems.append("mappings were re-granted by a user")
    return problems


