def _preflight(connection: sa.Connection) -> None:
    """Refuse to start if any table of this revision already exists.

    MySQL DDL commits implicitly, so an upgrade interrupted part-way leaves the tables
    it already created while ``alembic_version`` still says 0010. Starting again would
    fail on the first CREATE TABLE; this check stops before changing anything and says
    how to recover."""
    present = [
        r.table_name
        for r in _rows(
            connection,
            "SELECT table_name AS table_name FROM information_schema.tables "
            "WHERE table_schema = DATABASE() AND table_name IN :t",
            t=list(ALL_TABLES),
        )
    ]
    if present:
        raise RuntimeError(
            "Revision 0011 cannot start: these tables already exist "
            f"{sorted(present)} (probably from an interrupted earlier attempt). Nothing "
            "was changed. Restore the pre-migration backup, or - only after confirming "
            "they hold no data - have a DBA drop them, then run the upgrade again."
        )


def _seeded_scales_changed(connection: sa.Connection) -> list[str]:
    """The two seeded scales and their levels must be exactly as seeded, because the
    downgrade deletes them: administrators' edits would otherwise be lost silently."""
    problems: list[str] = []
    expected = {
        code: (name, gap_method, competent, plan_gap, [(r, c, lbl) for r, c, lbl in levels])
        for code, name, gap_method, competent, plan_gap, _note, levels in SCALES
    }
    for scale in _rows(
        connection,
        "SELECT id, code, name, gap_method, competent_rank, plan_gap_steps, version "
        "FROM proficiency_scale WHERE code IN :c",
        c=SCALE_CODES,
    ):
        name, gap_method, competent, plan_gap, levels = expected[scale.code]
        if (
            scale.version != 1
            or (scale.name, scale.gap_method, scale.competent_rank, scale.plan_gap_steps)
            != (name, gap_method, competent, plan_gap)
        ):
            problems.append(f"seeded scale {scale.code} was changed")
        actual = [
            (lvl.rank, lvl.code, lvl.label)
            for lvl in _rows(
                connection,
                "SELECT `rank` AS `rank`, code, label FROM proficiency_level "
                "WHERE scale_id = :s ORDER BY `rank`",
                s=scale.id,
            )
        ]
        if actual != levels:
            problems.append(f"levels of seeded scale {scale.code} were changed")
    return problems


def _downgrade_refusals(connection: sa.Connection) -> list[str]:
    reasons: list[str] = []
    for table in FEATURE_TABLES:
        if connection.execute(sa.text(f"SELECT 1 FROM `{table}` LIMIT 1")).first():  # noqa: S608
            reasons.append(f"{table} holds rows")
    others = _rows(
        connection, "SELECT code FROM proficiency_scale WHERE code NOT IN :c", c=SCALE_CODES
    )
    if others:
        reasons.append(f"additional proficiency scales exist {[o.code for o in others]}")
    reasons.extend(_seeded_scales_changed(connection))
    jobs = _rows(
        connection,
        "SELECT COUNT(*) AS n FROM import_job WHERE profile_code = 'organisation'",
    )
    if jobs and jobs[0].n:
        reasons.append(f"{jobs[0].n} organisation import job(s) exist")
    reasons.extend(seed_problems(connection))
    return reasons


